"""Write the adjacency fixture the Rust side checks itself against.

The model takes the normalized adjacency as an input, so Rust must build the
*same* matrix at play time that Python built during training. Two
implementations of one formula is exactly the setup that drifted between
govariants' TypeScript rules and this engine's Rust rules, so it gets the same
treatment: a fixture generated by one side and asserted by the other.

    python -m gvai.make_fixture

Edges come from real self-play files, so this covers whatever graph the Rust
engine actually emitted rather than a Python guess at it.
"""

from __future__ import annotations

import json
import pathlib

from .data import normalized_adjacency, read_game

# (fixture name, a self-play file to take the graph from)
SOURCES = [
    ("grid5", "data/grid5"),
    ("cube3", "data/cube3"),
]


def main() -> int:
    root = pathlib.Path(__file__).resolve().parents[2]
    out = root / "tests/fixtures/adjacency.json"
    fixtures = {}

    for name, directory in SOURCES:
        files = sorted((root / directory).glob("*.bin"))
        if not files:
            print(f"skipping {name}: no files in {directory}")
            continue
        game = read_game(files[0])
        adjacency = normalized_adjacency(game.num_nodes, game.edges)
        fixtures[name] = {
            "num_nodes": game.num_nodes,
            "source": str(files[0].relative_to(root)),
            # Rounded to keep the file readable; the Rust test compares with a
            # tolerance well above this.
            "adjacency": [round(float(v), 6) for v in adjacency.reshape(-1)],
        }
        print(f"{name}: {game.num_nodes} nodes from {files[0].name}")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(fixtures, indent=0))
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
